package com.overload.overload_server.workoutsession;

final class WorkoutSessionFailure extends RuntimeException {
    enum Reason {
        INVALID_REQUEST(400), AUTHENTICATION_REQUIRED(401), SESSION_NOT_FOUND(404), ROUTINE_NOT_FOUND(404),
        DATA_GENERATION_MISMATCH(409), SESSION_ID_CONFLICT(409), ACTIVE_SESSION_EXISTS(409),
        EDITOR_OWNERSHIP_LOST(409), SESSION_NOT_ACTIVE(409), SESSION_AUTO_CLOSED(409), WRITE_CONFLICT(409), CLOCK_CONTEXT_INVALID(422),
        REVISION_STALE(409), REVISION_PAYLOAD_MISMATCH(409), APPROVAL_REQUEST_ID_CONFLICT(409),
        APPROVAL_SEQUENCE_CONFLICT(409), RESOLUTION_CONFLICT(409), SOURCE_NOT_APPROVABLE(409), RECORD_ID_CONFLICT(409), FINISH_REQUEST_MISMATCH(409),
        SNAPSHOT_INCOMPLETE(422), INVALID_SNAPSHOT(422), IMMUTABLE_RECORD_CONTEXT(422), RECORD_DELETED(422),
        APPROVAL_SEQUENCE_GAP(422), RECORD_NOT_FOUND(404), EXERCISE_NOT_FOUND(404), PERFORMED_EXERCISE_IN_USE(422);

        final int status;
        Reason(int status) { this.status = status; }
    }

    final Reason reason;
    WorkoutSessionFailure(Reason reason) { super(reason.name()); this.reason = reason; }
}
